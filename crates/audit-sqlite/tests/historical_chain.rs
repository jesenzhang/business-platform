#![allow(clippy::expect_used, clippy::unwrap_used)]

//! Round 2c (PLAN-0014) historical audit compatibility on `SQLite`.
//!
//! `SQLite` stores audit timestamps as RFC 3339 text, so history can carry a
//! nanosecond tail that `PostgreSQL` `TIMESTAMPTZ` never could. Reading such a
//! row back must reproduce the exact digest it was signed with: `record_hash` is
//! recomputed on every `verify_chain`, so a reader that normalizes a hashed
//! timestamp reports intact history as a broken chain.
//!
//! Everything here goes through the real repository (`SqliteAuditStore::get`,
//! `SqliteAuditStore::verify_chain`, `append_sqlite`) over the real migration
//! catalog. The expected digest is a frozen literal produced by the historical
//! algorithm, never regenerated by the code under test.

use audit::{
    audit_chain_genesis, hash_record, AuditAction, AuditActor, AuditActorType, AuditChainScope,
    AuditChainVerification, AuditEvent, AuditQuery, AuditResource, AuditResult,
};
use audit_sqlite::{append_sqlite, SqliteAuditStore};
use chrono::{DateTime, Utc};
use sqlx::migrate::MigrateDatabase;
use sqlx::sqlite::SqlitePoolOptions;
use sqlx::SqlitePool;
use uuid::Uuid;

const HISTORICAL_TEXT: &str = "2026-09-26T12:00:00.123456789Z";
const HISTORICAL_NANOS: u32 = 123_456_789;
/// A nanosecond tail supplied to the *new* event constructor, which must
/// normalize it before signing because `PostgreSQL` could never store it.
const NEW_EVENT_NANOS: u32 = 555_555_555;
const HISTORICAL_ID: &str = "49ed89fe-7a4a-4c82-9b6a-3f1c2d5e6a01";
const HISTORICAL_TENANT: &str = "49ed89fe-7a4a-4c82-9b6a-3f1c2d5e6a02";
const HISTORICAL_ACTOR: &str = "49ed89fe-7a4a-4c82-9b6a-3f1c2d5e6a03";
const HISTORICAL_OPERATION: &str = "49ed89fe-7a4a-4c82-9b6a-3f1c2d5e6a04";
/// `record_hash` of the fixture row under the historical (pre-normalization)
/// algorithm, i.e. `SHA-256` over the canonical payload with both timestamps at
/// full nanosecond precision. Frozen once and independently re-hashed outside
/// this workspace: recomputing it here would make the assertion circular and
/// would keep passing even if reading history kept corrupting the row.
const HISTORICAL_RECORD_HASH: &str =
    "12b8823dbe1ea4ebaaf7896c676a52b790dbc004668166b203988e42f7cdf815";

fn parse(text: &str) -> DateTime<Utc> {
    DateTime::parse_from_rfc3339(text)
        .unwrap_or_else(|_| unreachable!("fixture instant {text} is valid RFC 3339"))
        .with_timezone(&Utc)
}

fn historical_instant() -> DateTime<Utc> {
    parse(HISTORICAL_TEXT)
}

fn uuid(value: &str) -> Uuid {
    Uuid::parse_str(value).unwrap_or_else(|_| unreachable!("fixture uuid is canonical"))
}

/// Real document `SQLite` migration catalog, which owns the shared
/// `audit_events` schema (001 base, 003 hashes, 006 chain columns).
async fn setup() -> SqlitePool {
    let path = std::env::temp_dir().join(format!("audit-sqlite-round2c-{}.db", Uuid::now_v7()));
    let url = format!("sqlite://{}", path.to_string_lossy().replace('\\', "/"));
    assert!(sqlx::Sqlite::create_database(&url).await.is_ok());
    let pool = SqlitePoolOptions::new()
        .max_connections(1)
        .connect(&url)
        .await
        .unwrap_or_else(|_| unreachable!("temporary SQLite pool must connect"));
    let migrated = document_sqlite::MIGRATOR.run(&pool).await;
    assert!(
        migrated.is_ok(),
        "document SQLite migrations must apply: {migrated:?}"
    );
    pool
}

/// Writes the fixture row the way a pre-normalization build left it in the
/// database: nanosecond text in both hashed timestamp columns and the digest the
/// historical algorithm produced.
async fn insert_historical_row(pool: &SqlitePool) {
    let tenant_id = uuid(HISTORICAL_TENANT);
    let sql = "INSERT INTO audit_events (id, tenant_id, action, resource_type, resource_id, \
               details, trace_id, created_at, occurred_at, recorded_at, stream_sequence, \
               chain_version, operation_id, actor_type, actor_id, correlation_id, causation_id, \
               reason, result, failure_code, before_hash, after_hash, changed_fields, \
               schema_version, previous_hash, record_hash) \
               VALUES (?1,?2,'document.created','document','doc-historical', \
               '{\"source\":\"round-2c\"}','trace-historical',?3,?3,?3,1,1,?4,'system',?5, \
               NULL,NULL,NULL,'succeeded',NULL,NULL,NULL,'[\"title\"]','audit.v1',?6,?7)";
    let result = sqlx::query(sql)
        .bind(HISTORICAL_ID)
        .bind(tenant_id.to_string())
        .bind(HISTORICAL_TEXT)
        .bind(HISTORICAL_OPERATION)
        .bind(HISTORICAL_ACTOR)
        .bind(audit_chain_genesis(tenant_id))
        .bind(HISTORICAL_RECORD_HASH)
        .execute(pool)
        .await;
    assert!(
        result.is_ok(),
        "historical fixture row must insert: {result:?}"
    );
}

fn scope(tenant_id: Uuid) -> AuditChainScope {
    AuditChainScope {
        tenant_id,
        from: None,
        to: None,
    }
}

/// A current-generation event whose `occurred_at` still carries a nanosecond
/// tail, i.e. exactly what `Utc::now()` hands the production write path.
fn new_event(tenant_id: Uuid) -> AuditEvent {
    AuditEvent::new(
        Uuid::now_v7(),
        tenant_id,
        AuditActor {
            actor_type: AuditActorType::Worker,
            actor_id: uuid(HISTORICAL_ACTOR),
        },
        AuditAction::new("document.chain-appended").unwrap_or_else(|_| unreachable!()),
        AuditResource::new("document", "doc-after-history").unwrap_or_else(|_| unreachable!()),
        Uuid::new_v4(),
        None,
        None,
        None,
        None,
        AuditResult::Succeeded,
        None,
        None,
        None,
        Vec::new(),
        serde_json::json!({"stage": "after-history"}),
        "audit.v1",
        parse("2026-09-26T12:00:00.555555555Z"),
    )
    .unwrap_or_else(|_| unreachable!())
}

async fn stored_text(pool: &SqlitePool, tenant_id: Uuid, column: &str, sequence: i64) -> String {
    let sql =
        format!("SELECT {column} FROM audit_events WHERE tenant_id = ?1 AND stream_sequence = ?2");
    sqlx::query_scalar::<_, String>(&sql)
        .bind(tenant_id.to_string())
        .bind(sequence)
        .fetch_one(pool)
        .await
        .unwrap_or_else(|_| {
            unreachable!("stored {column} for sequence {sequence} must be readable")
        })
}

#[tokio::test]
async fn repository_reverifies_a_historical_nanosecond_row() {
    let pool = setup().await;
    let tenant_id = uuid(HISTORICAL_TENANT);
    insert_historical_row(&pool).await;
    let store = SqliteAuditStore::new(pool.clone());

    // 1. The real read path preserves both hashed timestamps byte for byte.
    let event = store
        .get(tenant_id, uuid(HISTORICAL_ID))
        .await
        .unwrap_or_else(|_| unreachable!("repository read must succeed"))
        .unwrap_or_else(|| unreachable!("fixture row must be readable"));
    let stored_instant = historical_instant();
    assert_eq!(
        event.occurred_at(),
        stored_instant,
        "the repository must hand back the stored occurred_at unchanged"
    );
    assert_eq!(
        event.recorded_at(),
        stored_instant,
        "the repository must hand back the stored recorded_at unchanged"
    );
    assert_eq!(
        event.occurred_at().timestamp_subsec_nanos(),
        HISTORICAL_NANOS,
        "a nanosecond tail present in history must not be truncated on read"
    );

    // 2. The stored digest reproduces, and the chain verifies end to end.
    assert_eq!(
        hash_record(&event).unwrap_or_else(|_| unreachable!()),
        HISTORICAL_RECORD_HASH,
        "rehydrating a historically signed row must reproduce its record_hash"
    );
    let verification: AuditChainVerification = store
        .verify_chain(scope(tenant_id))
        .await
        .unwrap_or_else(|_| unreachable!("chain verification must run"));
    assert!(
        verification.valid,
        "intact nanosecond-precision history must verify: {verification:?}"
    );
    assert_eq!(verification.verified_count, 1, "{verification:?}");
    assert_eq!(verification.legacy_count, 0, "{verification:?}");

    // 3. A new append through the real write path chains onto that history.
    //    The new row is microsecond aligned by construction, the old row is not,
    //    and the boundary between the two must still verify.
    append_sqlite(&pool, &new_event(tenant_id))
        .await
        .unwrap_or_else(|_| unreachable!("append onto historical chain must succeed"));
    let after: AuditChainVerification = store
        .verify_chain(scope(tenant_id))
        .await
        .unwrap_or_else(|_| unreachable!("chain verification must run"));
    assert!(
        after.valid,
        "a microsecond-precision append must chain onto nanosecond history: {after:?}"
    );
    assert_eq!(after.verified_count, 2, "{after:?}");

    // 4. The freshly written row is microsecond aligned in storage, which is what
    //    makes it re-verifiable on PostgreSQL. The requested nanosecond tail was
    //    truncated before signing, not after.
    let occurred_column = stored_text(&pool, tenant_id, "occurred_at", 2).await;
    let recorded_column = stored_text(&pool, tenant_id, "recorded_at", 2).await;
    assert_eq!(
        parse(&occurred_column).timestamp_subsec_nanos(),
        NEW_EVENT_NANOS / 1_000 * 1_000,
        "a new event must be signed at microsecond precision: {occurred_column}"
    );
    assert_eq!(
        parse(&recorded_column).timestamp_subsec_nanos() % 1_000,
        0,
        "a newly appended hashed timestamp must be microsecond aligned: {recorded_column}"
    );

    pool.close().await;
}

#[tokio::test]
async fn tampering_with_the_historical_row_breaks_verification() {
    // Negative control for the test above: verification is live, so a payload
    // edit that leaves both timestamps and both hashes untouched is still caught.
    let pool = setup().await;
    let tenant_id = uuid(HISTORICAL_TENANT);
    insert_historical_row(&pool).await;
    let store = SqliteAuditStore::new(pool.clone());

    let before: AuditChainVerification = store
        .verify_chain(scope(tenant_id))
        .await
        .unwrap_or_else(|_| unreachable!("chain verification must run"));
    assert!(before.valid, "{before:?}");

    let edited = sqlx::query("UPDATE audit_events SET details = ?1 WHERE id = ?2")
        .bind("{\"source\":\"tampered\"}")
        .bind(HISTORICAL_ID)
        .execute(&pool)
        .await;
    assert!(edited.is_ok(), "tamper must apply: {edited:?}");

    let after: AuditChainVerification = store
        .verify_chain(scope(tenant_id))
        .await
        .unwrap_or_else(|_| unreachable!("chain verification must run"));
    assert!(
        !after.valid,
        "an edited historical payload must not verify: {after:?}"
    );
    assert_eq!(
        after.first_broken_id,
        Some(uuid(HISTORICAL_ID)),
        "{after:?}"
    );

    pool.close().await;
}
